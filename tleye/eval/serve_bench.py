"""Latency of a running TLEye service (sequential requests, the two example solutions). Appends one row per run to reports/serving.md.
    python -I -m tleye.eval.serve_bench --url http://localhost:8000 --label "docker, LightGBM, M2 (Colima 4 CPU)" [--n 30]"""
import argparse
import json
import platform
import time
import urllib.request
from pathlib import Path

STATEMENT = "<h3>Constraints</h3><ul><li>2 \\leq N \\leq 2 \\times 10^5</li><li>1 \\leq A_i \\leq 10^9</li></ul>"
OUT = Path("reports/serving.md")
HEADER = ["# Serving latency (script-generated by tleye/eval/serve_bench.py)", "",
          "Sequential POST /check requests on the two example solutions in tleye/examples (C++, about 20 lines each), after start-up. "
          "Round-trip time measured by the client on the same machine; the model is loaded once per process.", "",
          "| setup | model | requests | p50 ms | p95 ms | max ms | outcomes |", "|---|---|---|---|---|---|---|"]


def post(url: str, payload: dict) -> dict:
    req = urllib.request.Request(f"{url}/check", json.dumps(payload).encode(), {"Content-Type": "application/json"})
    return json.load(urllib.request.urlopen(req, timeout=300))


def main(url: str, label: str, n: int) -> None:
    model = json.load(urllib.request.urlopen(f"{url}/health"))["model"]
    times, outcomes = [], set()
    for name in ("slow", "fast"):
        payload = {"code": Path(f"tleye/examples/p02779_{name}.cpp").read_text(), "language": "C++", "statement_html": STATEMENT, "time_limit_ms": 2000}
        post(url, payload)                                   # warm-up, not timed
        for _ in range(n):
            t = time.perf_counter(); r = post(url, payload); times.append((time.perf_counter() - t) * 1000)
        outcomes.add(f"{name}: {r['outcome']} ({r['p_tle_model']})")
    times.sort()
    q = lambda f: times[min(len(times) - 1, int(f * len(times)))]  # noqa: E731
    row = f"| {label} | {model} | {len(times)} | {q(0.5):.0f} | {q(0.95):.0f} | {times[-1]:.0f} | {'; '.join(sorted(outcomes))} |"
    lines = OUT.read_text().splitlines() if OUT.exists() else HEADER
    lines = [ln for ln in lines if not ln.startswith(f"| {label} | {model} |")] + [row]
    OUT.write_text("\n".join(lines) + "\n"); print(row, "| client:", platform.platform())


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--url", default="http://localhost:8000"); ap.add_argument("--label", required=True); ap.add_argument("--n", type=int, default=30)
    a = ap.parse_args(); main(a.url.rstrip("/"), a.label, a.n)
